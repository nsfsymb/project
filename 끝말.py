    if recommendations:
        st.success(f"**'{user_input}'**(으)로 시작하는 강력한 방어/공격 단어 {len(recommendations)}개 발견!")
        
        for word in recommendations:
            st.info(f"💡 **{word}** (끝 단어 공격 유효)")
    else:
        st.warning(f"앗, '{user_input}'로 시작하는 등록된 한방단어가 없습니다. 다른 글자를 입력해보세요!")
