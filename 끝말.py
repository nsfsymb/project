# 실시간 크롤링 함수 (가장 안전하게 웹 데이터를 긁어옵니다)
@st.cache_data(show_spinner="웹사이트에서 전체 한방단어를 긁어오는 중... (처음 한 번만 실행됩니다)")
def load_all_hanbang_words():
    all_dict = {}
    
    for char in CHO_LIST:
        url = f"https://koreanwordfinder.com/hanbang/page/first-letter-start.php?first_letter={char}"
        try:
            response = requests.get(url, timeout=5)
            if response.status_code == 200:
                soup = BeautifulSoup(response.text, 'html.parser')
                
                # strong 태그나 특정 클래스명 내부의 단어 텍스트 추출
                words = []
                for item in soup.find_all(['strong', 'b']):
                    text = item.get_text().strip()
                    # 괄호나 번호 제거 ([1] 단어 형태 대응)
                    if text and not text.startswith('[') and not text.replace('.', '').isdigit():
                        # 깔끔하게 단어만 추출 (공백이나 특수문자 정제)
                        clean_word = text.split(':')[0].strip() if ':' in text else text
                        if clean_word and len(clean_word) > 1: # 한 글자 단어 제외
                            words.append(clean_word)
                
                # 중복 제거 후 저장
                if words:
                    all_dict[char] = list(set(words))
        except Exception:
            # 타임아웃이나 오류 발생 시 해당 글자는 패스
            continue
            
    return all_dict

# 딕셔너리 데이터 가져오기
HANBANG_DICT = load_all_hanbang_words()

